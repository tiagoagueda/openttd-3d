#!/bin/sh
# Compile the 3D viewport shaders into C headers for every backend we can target from here.
#
# Usage: compile_shaders.sh /path/to/shaderc /path/to/bgfx/src
#
# shaderc is bgfx's shader compiler; build it from bgfx.cmake with -DBGFX_BUILD_TOOLS=ON.
# The second argument is the directory that holds bgfx_shader.sh.
#
# Direct3D shaders can only be compiled on Windows and are not generated here.

set -e

SHADERC="$1"
BGFX_SRC="$2"
if [ ! -x "$SHADERC" ] || [ ! -f "$BGFX_SRC/bgfx_shader.sh" ]; then
	echo "Usage: $0 /path/to/shaderc /path/to/bgfx/src" >&2
	exit 1
fi

cd "$(dirname "$0")"

# compile <name> <vertex|fragment>
compile() {
	out="$1.bin.h"
	{
		echo "/* Generated by compile_shaders.sh from $1.sc; do not edit. */"
		echo
	} > "$out"
	# suffix:platform:profile
	for target in glsl:linux:330 essl:android:300_es spv:linux:spirv mtl:osx:metal; do
		suffix="${target%%:*}"
		rest="${target#*:}"
		platform="${rest%%:*}"
		profile="${rest#*:}"
		"$SHADERC" -f "$1.sc" -o "$out.tmp" --type "$2" --platform "$platform" -p "$profile" \
			--varyingdef varying.def.sc -i "$BGFX_SRC" --bin2c "$1_$suffix"
		cat "$out.tmp" >> "$out"
		rm "$out.tmp"
	done
}

compile vs_terrain vertex
compile fs_terrain fragment
